#ifndef TESTREFCHECKCOMPAREALL_HPP_
#define TESTREFCHECKCOMPAREALL_HPP_

#include <cxxtest/TestSuite.h>

#include <iostream>
#include <string>

#include "RefCheckManifest.hpp"
#include "Exception.hpp"
#include "RunAndCheckIonicModels.hpp"

// This test must run sequentially (never in parallel), like other codegen tests.
#include "FakePetscSetup.hpp"

/**
 * Numerically diffs every chaste_codegen reference-model "variant" rendering (the current
 * branch's unsuffixed file, plus any --sympy_X_Y / --python_X_Y variant) against the frozen
 * baseline (chaste-codegen's `master`-branch rendering of the same (scheme, model), see
 * freeze_baseline.py), to verify that textually different but supposedly
 * mathematically-equivalent generated code actually simulates to the same result.
 *
 * The manifest (which (scheme, model, variant) tuples exist, and whether a baseline was found for
 * them) is generated by generate_refcheck_harness.py into RefCheckManifest.hpp. The .dat files
 * being compared here are written by the per-tuple Test_RefCheck_*.hpp suites generated into the
 * sibling RefCheck_<scheme>_<model>_<variant> projects; this test's CMakeLists.txt declares an explicit
 * ctest DEPENDS on all of them so they always run first.
 */
class TestRefCheckCompareAll : public CxxTest::TestSuite
{
public:
    void TestCompareAllVariantsAgainstBaseline()
    {
        const double tolerance = 1e-3; // mV; tight, since same-scheme variants are claimed
                                        // to be exactly mathematically equivalent renderings.
        std::vector<RefCheckEntry> entries = GetRefCheckManifest();

        unsigned num_pass = 0;
        unsigned num_fail = 0;
        unsigned num_no_baseline = 0;
        unsigned num_error = 0;

        std::cout << "\n=== CodegenRefCheck: comparing every current-branch variant against "
                  << "the frozen baseline ===\n";

        for (unsigned i = 0; i < entries.size(); i++)
        {
            const RefCheckEntry& r_entry = entries[i];
            const std::string label = r_entry.scheme + "/" + r_entry.model + " [" + r_entry.variant + "]";

            if (!r_entry.hasBaseline)
            {
                std::cout << "NO-BASELINE  " << label << "\n";
                num_no_baseline++;
                continue;
            }

            const std::string folder = "CodegenRefCheck/" + r_entry.scheme + "/" + r_entry.model;
            try
            {
                unsigned num_failed_before = CxxTest::tracker().testFailedAsserts();
                // r_entry.variant doubles as the .dat basename the matching RefCheck_* tuple project
                // wrote into `folder` (see write_tuple_project() in generate_refcheck_harness.py)
                // - here it picks out which rendering's .dat to diff against "baseline"'s.
                CompareCellModelResults("baseline", r_entry.variant, tolerance, /*vOnly=*/true, folder);
                if (CxxTest::tracker().testFailedAsserts() > num_failed_before)
                {
                    std::cout << "FAIL         " << label << "\n";
                    num_fail++;
                }
                else
                {
                    std::cout << "PASS         " << label << "\n";
                    num_pass++;
                }
            }
            catch (Exception& e)
            {
                // Most commonly: no .dat file (e.g. a CVODE-only model on a build without
                // CHASTE_CVODE, or a reference file that failed to compile) rather than a
                // genuine numerical mismatch - report distinctly, don't fail the whole suite.
                std::cout << "ERROR        " << label << ": " << e.GetMessage() << "\n";
                num_error++;
            }
        }

        std::cout << "=== CodegenRefCheck summary: " << num_pass << " pass, " << num_fail
                  << " fail, " << num_no_baseline << " no-baseline, " << num_error << " error, "
                  << entries.size() << " total ===\n";

        TS_ASSERT_EQUALS(num_fail, 0u);
    }
};

#endif // TESTREFCHECKCOMPAREALL_HPP_
